model_performance = []

for t in thresholds:
    pred = (positive_class >= t).astype(int)

    tn, fp, fn, tp = confusion_matrix(y_val, pred, labels=[0, 1]).ravel()
    Threshold= t
    Accuracy= accuracy_score(y_val, pred)
    Precision= precision_score(y_val, pred)
    Recall = recall_score(y_val, pred)
    F1_Score = f1_score(y_val, pred)

    model_performance.append({"Threshold": Threshold,
                              "TN" : tn,
                              "FP": fp,
                              "FN": fn,
                              "TP": tp,
                             "Accuracy": Accuracy,
                              " Precision":  Precision,
                              "Recall" : Recall,
                              "F1_Score" : F1_Score})

thresholds_df = pd.DataFrame(model_performance)
thresholds_df.to_csv("outputs/part_c_thresholds.csv",index=False)

