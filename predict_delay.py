import os
os.makedirs("data",exist_ok=True)
os.makedirs("models",exist_ok=True)
os.makedirs("outputs",exist_ok=True)
os.makedirs("src",exist_ok=True)

import pandas as pd
import joblib

raw_shipments = pd.read_csv("/content/data/raw_shipments.csv")
hubs = pd.read_csv("/content/data/hubs.csv")

from src.shipment_prep import clean_shipments, build_features

new_shipments = pd.read_csv("data/new_shipments.csv")

hubs = pd.read_csv("data/hubs.csv")

model = joblib.load("models/delay_model.pkl")

threshold_df = pd.read_csv("models/delay_threshold.csv")

feature_order_df = pd.read_csv("models/feature_order.csv")

impute_values_df = pd.read_csv("models/impute_values.csv")

hub_segments = pd.read_csv("outputs/hub_segments.csv")

threshold = threshold_df["threshold"].iloc[0]

feature_order = feature_order_df["feature"].tolist()

import numpy as np

medians = dict(zip(impute_values_df["feature"],impute_values_df["median"]))

clean_new, _ = clean_shipments(new_shipments, medians=medians)

new_features = build_features(clean_new, hubs)

X_new = new_features[feature_order]

delay_probability = model.predict_proba(X_new)[:, 1]

delay_probability = delay_probability.round(4)

flagged = (delay_probability >= threshold).astype(int)

results = new_features[
    ["shipment_id", "hub_id"]
].copy()

results["delay_probability"] = delay_probability

results["flagged"] = flagged

results = results.merge(
    hub_segments[["hub_id", "segment"]],
    on="hub_id",
    how="left",
    sort=False
)

conditions = [
    (results["flagged"] == 1) &
    (results["segment"] == "Escalate"),

    (results["flagged"] == 1)
]

choices = [
    "Escalate to hub manager",
    "Proactive customer call"
]

results["action"] = np.select(
    conditions,
    choices,
    default="No action")

results = results[
    [
        "shipment_id",
        "hub_id",
        "segment",
        "delay_probability",
        "flagged",
        "action"
    ]
]

results.to_csv("outputs/new_shipment_actions.csv",index=False)