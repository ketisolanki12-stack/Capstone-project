import os
os.makedirs("data",exist_ok=True)

import pandas as pd
df = pd.read_csv("/content/data/modelling_table.csv")

df.columns

import numpy as np
import os

hub_profile = df.groupby("hub_id").agg(shipments=("shipment_id","count"),
                  mean_delivery_hours=("delivery_hours","mean"),
                  delay_rate=("is_delayed", "mean"),
                  mean_distance_km= ("distance_km","mean"),
                  mean_n_stops= ("n_stops","mean"),
                  hub_city=("hub_city", "first"),
                  hub_tier=("hub_tier", "first")).reset_index()

hub_profile = hub_profile.sort_values(by="hub_id", ascending=True)

os.makedirs("outputs",exist_ok=True)
hub_profile.to_csv("outputs/hub_profile.csv",index=False)

from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler

features = ["mean_delivery_hours",
            "delay_rate",
            "mean_distance_km",
            "mean_n_stops"]
X = hub_profile[features]

sc = StandardScaler()
X_scaled = sc.fit_transform(X)

X_scaled = pd.DataFrame(
    X_scaled,
    columns=features)

model = KMeans(n_clusters=3,random_state=42,n_init=10)
model.fit(X_scaled)

X_scaled.head()

from sklearn.metrics.pairwise import euclidean_distances

K = [2, 3, 4, 5]

final_results = []

for k in K:

    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    kmeans.fit(X_scaled)

    labels = kmeans.labels_

    distance_matrix = euclidean_distances(X_scaled)

    within_distance = []
    across_distance = []

    for i in range(24):
        for j in range(i+1, 24):

            if labels[i] == labels[j]:
                within_distance.append(distance_matrix[i, j])
            else:
                across_distance.append(distance_matrix[i, j])

    within_distance = np.mean(within_distance)
    across_distance = np.mean(across_distance)

    ratio = across_distance / within_distance

    cluster_sizes = "-".join(
        map(str, pd.Series(labels).value_counts().sort_values(ascending=False))
    )

    final_results.append([k, ratio, cluster_sizes])


results_df = pd.DataFrame(
    final_results,
    columns=["K", "across_over_within", "cluster_sizes"]
)

results_df.to_csv("outputs/part_d_separation.csv",index=False)

hub_profile["Cluster"] = model.predict(X_scaled)

cluster_delay = hub_profile.groupby("Cluster")["delay_rate"].mean()

sorted_clusters = cluster_delay.sort_values().index.tolist()

segment_names = ["Standard", "Watch", "Escalate"]

cluster_mapping = dict(zip(sorted_clusters, segment_names))

hub_profile["segment"] = hub_profile["Cluster"].map(cluster_mapping)

hub_segments = hub_profile[["hub_id", "segment", "hub_city", "hub_tier"]]

hub_segments.to_csv(
    "outputs/hub_segments.csv",
    index=False
)
hub_segments

