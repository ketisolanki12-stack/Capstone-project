bins = [0, 200, 400, 600, 2000]
labels = ["0-200","201-400","401-600","601+"]

df["distance_band"] = pd.cut(
    df["distance_km"],
    bins=bins,
    labels=labels,
    right=True)
def aggregate_dimension(df, group_col):
  agg = (
        df.groupby(group_col, observed=False)
        .agg(
            shipments=("is_delayed", "count"),
            delayed=("is_delayed", "sum"),
            delay_rate=("is_delayed", "mean"),
            mean_hours=("delivery_hours", "mean"),
        )
        .reset_index()
       )
  agg = agg.rename(columns={group_col: "group"})
  agg.insert(0, "dimension", group_col)

  return agg

group_service = aggregate_dimension(df, "service_type")
group_tier = aggregate_dimension(df, "hub_tier")
group_distance = aggregate_dimension(df, "distance_band")

delay_evidence = pd.concat(
    [group_service, group_tier, group_distance], ignore_index=True
)

